/* Паллета для продажников по рубрике товара (29.09.2026, тестово).

   Рахманов: в бэклоге Данилово ~6000 паллет и 170 тыс. уценённых товаров, на
   каждом 30–40 с уходит на поиск категории на сайте. Степан: пикалка и так
   даёт рубрику — «можно ли сразу показывать как название паллеты для
   продажников… где спорно пиши спорно».

   Соответствие снято с остатков 29.09 (брак и отремонтированное в паллетах ДМД,
   рубрика сайта Dim_Product.9901_Name): на паллетах «ФБ-…» одна рубрика на
   97–99 %. Спорно — где своей паллеты в ДМД нет или паллета смешанная.
   Ключ — рубрика ВИТРИНЫ (как в данных пикалки, до переименования для показа). */
(function () {
  "use strict";

  const TOCHNO = {
    "Все для сада": "ФБ-Сад",
    "Товары для офиса и дома": "ФБ-ОД",
    "Сантехника": "ФБ-Сантехника",
    "Складское оборудование": "ФБ-Складское Оборудование",
    "Электрика и свет": "ФБ-Эл Свет",
    "Автогаражное оборудование": "ФБ-Авто",
    "Клининговое оборудование": "ФБ-Клининг",
    "Товары для отдыха": "ФБ-Спорт и Туризм",
    "Климатическое оборудование": "ФБ-Климат",
    "Строительное оборудование": "ФБ - Строительное оборудование",
    "Строительные материалы": "ФБ-отделочные-материалы",
    "Станки": "ФБ-Станки",
    // 30.09 вечер — по сверке с остатками паллет (Боева, Чударов): расходники в РМ(ОБЩ) 97 %,
    // крепёж в КрепФур(ОБЩ) 98 %, СИЗ в СИЗ(ОБЩ); «ФБ-РМ» и «РМ УЦЕНКА» почти не заводят.
    "Расходные материалы": "РМ(ОБЩ)",
    "Крепеж": "КрепФур(ОБЩ)",
    "Спецодежда и СИЗ": "СИЗ(ОБЩ)",
  };
  const SPORNO = {
    "Инструмент": { imya: "Инст(РАБ) / Инст(НЕРАБ)", pochemu: "рабочий — РАБ, нерабочий — НЕРАБ" },
    "Ручной инструмент": { imya: "Руч(КРИТ) / Руч(КОСМ)", pochemu: "крит — КРИТ, косм — КОСМ" },
  };
  // По названию, где рубрика шире паллеты (на остатках: радиаторы 99 %, лестницы 98 %, рохли 85 %).
  const PO_IMENI = [
    [/радиатор|полотенцесушител/i, "Рад(ОБЩ)", ["Сантехника", "Климатическое оборудование"]],
    [/рохл|тележк\S*\s+гидравлич|гидравлическ\S*\s+тележк|штабелер/i, "Рохли(ОБЩ)", ["Складское оборудование"]],
    [/лестниц|стремянк/i, "ЛестСтр(ОБЩ)", ["Все для сада", "Строительное оборудование", "Складское оборудование"]],
  ];
  // АКБ: слово в имени (бренд стоит первым — «FIRE BALL Аккумулятор 6ст»), не инструмент и не сад —
  // аккумуляторы к инструменту кладут к инструменту. На остатках: ловит 87 %, точность 91 %.
  const AKB_SLOVO = /(?:^|[\s(])(аккумулятор(?:ы)?|аккумуляторн\S*\s+батар+е\S*|батар+е\S*\s+аккумуляторн\S*|тяговые\s+аккумуляторные|батарейк\S*|элемент\S*\s+питания|акб)(?=[\s,.)\-]|$)|(?:^|\s)6\s?ст\s?-?\s?\d/i;
  const AKB_NE = /зарядн|без\s+акб|для\s+акб|\d\s*акб|ареометр|тестер|(?:^|\s)мобильн\S*\s+аккумулятор|аккумулятор\S*\s+холода/i;

  // Пикалка показывает рубрику по-каталожному (script.js, RUBRIC_ALIASES) — принимаем и так.
  const KATALOG = {
    "Сантехника и инженерные системы": "Сантехника", "Офис и дом": "Товары для офиса и дома",
    "Крепёж и фурнитура": "Крепеж", "Автотовары": "Автогаражное оборудование",
    "Станки и промкомпоненты": "Станки", "Отделочные и стройматериалы": "Строительные материалы",
    "Всё для сада": "Все для сада", "Спорт и туризм": "Товары для отдыха", "Склад": "Складское оборудование",
    "Клининг и химия": "Клининговое оборудование", "Климат, отопление и вентиляция": "Климатическое оборудование",
  };

  /** rubrika — рубрика витрины или каталога, klaster — «1»…«4» или подпись кластера. */
  window.PalletaProdazh = function (rubrika, klaster, cena, imya) {
    // 30.09: «все аккумуляторы, даже если это расходный материал, идут в аккумуляторы».
    const t = String(imya || "").trim();
    const r0 = KATALOG[String(rubrika || "").trim()] || String(rubrika || "").trim();
    if (t && AKB_SLOVO.test(t) && !AKB_NE.test(t) && r0 !== "Инструмент" && r0 !== "Все для сада") {
      return { imya: "АКБ(ОБЩ)", sporno: false, pochemu: "аккумулятор — всегда в АКБ" };
    }
    // 30.09 Степан: «все товары до 1000 это мистери бокс» — паллеты «МисБокс-…».
    const c = Number(String(cena == null ? "" : cena).replace(/\s/g, "").replace(",", "."));
    if (c > 0 && c < 1000) return { imya: "МисБокс", sporno: false, pochemu: "цена до 1 000 ₽ — мистери бокс" };
    let r = String(rubrika || "").trim();
    r = KATALOG[r] || r;
    const k = String(klaster || "").trim();
    if (/^4\b/.test(k)) return { imya: "КРГБ", sporno: false, pochemu: "крупногабарит — по кластеру 4" };
    for (const [rx, kuda, rubriki] of PO_IMENI) if (rubriki.includes(r) && rx.test(t)) return { imya: kuda, sporno: false, pochemu: "по названию" };
    if (TOCHNO[r]) return { imya: TOCHNO[r], sporno: false, pochemu: "" };
    if (SPORNO[r]) return { imya: SPORNO[r].imya, sporno: false, pochemu: SPORNO[r].pochemu };
    return r ? { imya: "нет своей паллеты", sporno: true, pochemu: `для рубрики «${r}» паллеты в ДМД не нашлось` } : null;
  };
})();

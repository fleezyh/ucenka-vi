/* Паллета для продажников по рубрике товара (29.09.2026, тестово).

   Рахманов: в бэклоге Данилово ~6000 паллет и 170 тыс. уценённых товаров, на
   каждом 30–40 с уходит на поиск категории на сайте. Степан: пикалка и так
   даёт рубрику — «можно ли сразу показывать как название паллеты для
   продажников… где спорно пиши спорно».

   Соответствие снято с остатков 29.09 (брак и отремонтированное в паллетах ДМД,
   рубрика сайта Dim_Product.9901_Name): на паллетах «ФБ-…» одна рубрика на
   97–99 %. Спорно — где своей паллеты в ДМД нет или паллета смешанная.
   Ключ — рубрика ВИТРИНЫ (как в данных пикалки, до переименования для показа). */
(function () {
  "use strict";

  const TOCHNO = {
    "Все для сада": "ФБ-Сад",
    "Товары для офиса и дома": "ФБ-ОД",
    "Сантехника": "ФБ-Сантехника",
    "Складское оборудование": "ФБ-Складское Оборудование",
    "Электрика и свет": "ФБ-Эл Свет",
    "Автогаражное оборудование": "ФБ-Авто",
    "Клининговое оборудование": "ФБ-Клининг",
    "Товары для отдыха": "ФБ-Спорт и Туризм",
    "Климатическое оборудование": "ФБ-Климат",
    "Строительное оборудование": "ФБ - Строительное оборудование",
    "Строительные материалы": "ФБ-отделочные-материалы",
    "Станки": "ФБ-Станки",
    // 30.09 вечер — по сверке с остатками паллет (Боева, Чударов): расходники в РМ(ОБЩ) 97 %,
    // крепёж в КрепФур(ОБЩ) 98 %, СИЗ в СИЗ(ОБЩ); «ФБ-РМ» и «РМ УЦЕНКА» почти не заводят.
    "Расходные материалы": "РМ(ОБЩ)",
    "Крепеж": "КрепФур(ОБЩ)",
    "Спецодежда и СИЗ": "СИЗ(ОБЩ)",
  };
  const SPORNO = {
    "Инструмент": { imya: "Инст(РАБ) / Инст(НЕРАБ)", pochemu: "рабочий — РАБ, нерабочий — НЕРАБ" },
    "Ручной инструмент": { imya: "Руч(КРИТ) / Руч(КОСМ)", pochemu: "крит — КРИТ, косм — КОСМ" },
  };
  // По названию, где рубрика шире паллеты (на остатках: радиаторы 99 %, лестницы 98 %, рохли 85 %).
  const PO_IMENI = [
    // 09.10: масляные радиаторы (рубрика «Климатическое оборудование») — в ФБ-Климат, «Рад» — только сантехника
    [/радиатор|полотенцесушител/i, "Рад(ОБЩ)", ["Сантехника"]],
    [/рохл|тележк\S*\s+гидравлич|гидравлическ\S*\s+тележк|штабелер/i, "Рохли(ОБЩ)", ["Складское оборудование"]],
    [/лестниц|стремянк/i, "ЛестСтр(ОБЩ)", ["Все для сада", "Строительное оборудование", "Складское оборудование"]],
  ];
  // АКБ: слово в имени (бренд стоит первым — «FIRE BALL Аккумулятор 6ст»), не инструмент и не сад —
  // аккумуляторы к инструменту кладут к инструменту. На остатках: ловит 87 %, точность 91 %.
  const AKB_SLOVO = /(?:^|[\s(])(аккумулятор(?:ы)?|аккумуляторн\S*\s+батар+е\S*|батар+е\S*\s+аккумуляторн\S*|тяговые\s+аккумуляторные|батарейк\S*|элемент\S*\s+питания|акб)(?=[\s,.)\-]|$)|(?:^|\s)6\s?ст\s?-?\s?\d/i;
  const AKB_NE = /зарядн|без\s+акб|для\s+акб|\d\s*акб|ареометр|тестер|(?:^|\s)мобильн\S*\s+аккумулятор|аккумулятор\S*\s+холода/i;

  // Пикалка показывает рубрику по-каталожному (script.js, RUBRIC_ALIASES) — принимаем и так.
  const KATALOG = {
    "Сантехника и инженерные системы": "Сантехника", "Офис и дом": "Товары для офиса и дома",
    "Крепёж и фурнитура": "Крепеж", "Автотовары": "Автогаражное оборудование",
    "Станки и промкомпоненты": "Станки", "Отделочные и стройматериалы": "Строительные материалы",
    "Всё для сада": "Все для сада", "Спорт и туризм": "Товары для отдыха", "Склад": "Складское оборудование",
    "Клининг и химия": "Клининговое оборудование", "Климат, отопление и вентиляция": "Климатическое оборудование",
  };

  /** rubrika — рубрика витрины или каталога, klaster — «1»…«4» или подпись кластера. */
  window.PalletaProdazh = function (rubrika, klaster, cena, imya, krit) {
    // 12.10: опасные отходы — утиль, основным выбором (Степан: «не снизу»)
    const op = window.OpasnyeOthody ? window.OpasnyeOthody(imya) : "";
    if (op) return { imya: window.UTIL_OPAS, sporno: false, pochemu: `опасные отходы: ${op}`, opasnye: op };
    // 02.10: «маркетплейс — товар дороже 10к и с минимальными повреждениями». Косм — туда; крит — по рубрике;
    // не знаем — оба варианта.
    const c0 = Number(String(cena == null ? "" : cena).replace(/\s/g, "").replace(",", "."));
    const p0 = poRubrike(rubrika, klaster, cena, imya);
    if (c0 >= 10000 && !(p0 && /^(АКБ|МисБокс)/.test(p0.imya))) {
      const kk = String(krit || "").toLowerCase();
      if (/косм/.test(kk)) return { imya: "Маркетплейс", sporno: false, pochemu: "дороже 10 000 ₽, повреждения минимальные" };
      if (!/крит/.test(kk)) {
        const ost = p0 && !/^нет своей/.test(p0.imya) ? p0.imya : "";
        return { imya: ost ? `Маркетплейс / ${ost}` : "Маркетплейс", sporno: true,
          pochemu: `дороже 10 000 ₽: повреждения минимальные — Маркетплейс${ost ? `, иначе — ${ost}` : ""}` };
      }
    }
    return p0;
  };
  function poRubrike(rubrika, klaster, cena, imya) {
    // 30.09: «все аккумуляторы, даже если это расходный материал, идут в аккумуляторы».
    const t = String(imya || "").trim();
    const r0 = KATALOG[String(rubrika || "").trim()] || String(rubrika || "").trim();
    if (t && AKB_SLOVO.test(t) && !AKB_NE.test(t) && r0 !== "Инструмент" && r0 !== "Все для сада") {
      return { imya: "АКБ(ОБЩ)", sporno: false, pochemu: "аккумулятор — всегда в АКБ" };
    }
    // 30.09 Степан: «все товары до 1000 это мистери бокс» — паллеты «МисБокс-…».
    const c = Number(String(cena == null ? "" : cena).replace(/\s/g, "").replace(",", "."));
    if (c > 0 && c < 1000) return { imya: "МисБокс", sporno: false, pochemu: "цена до 1 000 ₽ — мистери бокс" };
    let r = String(rubrika || "").trim();
    r = KATALOG[r] || r;
    const k = String(klaster || "").trim();
    if (/^4\b/.test(k)) return { imya: "КРГБ", sporno: false, pochemu: "крупногабарит — по кластеру 4" };
    for (const [rx, kuda, rubriki] of PO_IMENI) if (rubriki.includes(r) && rx.test(t)) return { imya: kuda, sporno: false, pochemu: "по названию" };
    if (TOCHNO[r]) return { imya: TOCHNO[r], sporno: false, pochemu: "" };
    if (SPORNO[r]) return { imya: SPORNO[r].imya, sporno: false, pochemu: SPORNO[r].pochemu };
    return r ? { imya: "нет своей паллеты", sporno: true, pochemu: `для рубрики «${r}» паллеты в ДМД не нашлось` } : null;
  }

  /* 08.10 Степан: «ГСМ надо как-то отделить (мы их не продаём) и подсвечивать». Список — коды сайта
     товаров из категорий масел, смазок и технических жидкостей (gsm_spisok.py на сервере, раз в сутки). */
  let gsm = null;
  fetch("/data/gsm.json", { cache: "default" }).then((o) => (o.ok ? o.json() : null))
    .then((d) => { gsm = new Set(((d && d.kod) || []).map(String)); document.dispatchEvent(new CustomEvent("gsm:gotov")); })
    .catch(() => { gsm = new Set(); });
  window.GSM = {
    est: (kod) => Boolean(gsm && kod && gsm.has(String(kod).trim())),
    palleta: { imya: "ГСМ — не продаём", sporno: false, pochemu: "масла, смазки, техжидкости — в паллету продаж не класть", gsm: true },
  };

  /* 12.10 Утиль — опасные отходы (таблички мест накопления «Надписи для лмп.docx»): ртутные лампы (I класс), светодиодные
     лампы и светильники, лампы накаливания, батарейки, литий-ионные и свинцовые аккумуляторы (II класс).
     Степан: «инст не может быть этим отходом» — только сам товар-отход, не инструмент и оборудование с АКБ внутри;
     «надо говорить, что это утиль — основным выбором, а не снизу». Что за товар — по «голове» названия: первые слова после
     бренда («AEG Аккумулятор 18В…», «Osram Лампа …»). Те же правила — palleta_prodazh.opasnye на сервере (сверено: 0 расхождений).
     Граница слова для кириллицы — свои lookaround: \b в JS понимает только латиницу. */
  const NK = "(?![а-яёa-z0-9])", NZ = "(?<![а-яёa-z0-9])";
  const O_LAMPA = /^(?:лампа|лампы|лампочк[а-яё]*|эл\.?\s*лампа|автолампа|автолампы|светодиодн[а-яё]*\s+ламп[а-яё]*|люминесцентн[а-яё]*\s+ламп[а-яё]*|линейн[а-яё]*\s+люминесцентн[а-яё]*|компактн[а-яё]*\s+люминесцентн[а-яё]*)$/iu;
  const O_SVET = /^(?:светильник[\p{L}\p{N}_]*|прожектор[\p{L}\p{N}_]*|светодиодн[а-яё]*\s+(?:светильник|прожектор)[\p{L}\p{N}_]*|led-?светильник[\p{L}\p{N}_]*)$/iu;
  const O_AKK = /^(?:аккумулятор|аккумуляторы|акб|аккумуляторн[а-яё]*\s+батаре[а-яё]*|батаре[а-яё]*\s+аккумуляторн[а-яё]*|внешн[а-яё]*\s+аккумулятор|power\s?bank|пауэрбанк)$/iu;
  const O_BAT = /^(?:батарейк[а-яё]*|элемент[а-яё]*\s+питания|литиев[а-яё]*\s+батарейк[а-яё]*)$/iu;
  const O_NE = new RegExp("патрон|корпус|" + NZ + "пра" + NK + "|дроссел|балласт|зарядн|клемм|тестер|ареометр|держател|адаптер|переходник|кабел|провод|кронштейн|без\\s+(?:акб|аккум|ламп|батар)|для\\s+(?:ламп|акб|аккумулятор|батар)", "iu");
  const O_LITIY = /li-?ion|li-?pol|lifepo|литий|литиев|\bli\b/iu;
  const O_SVINEC = new RegExp("свинцов|кислот|\\bagm\\b|гелев|(?:^|\\s)6\\s?ст|стартерн|автомобильн|мото|для\\s+ибп|\\bvrla\\b|тягов|\\bcsb\\b", "iu");
  const O_12V = new RegExp("(?<!\\d)(?:12|6)\\s?[vв]" + NK, "iu");
  const O_RTUT = new RegExp("люминесцент|ртут|энергосберегающ|" + NZ + "(?:клл|дрл|дрв|днат)" + NK + "|натриев|металлогалоген|газоразрядн|бактерицидн", "iu");
  const O_LED = new RegExp("светодиод|\\bled\\b|сд" + NK, "iu");
  const golova = (t, n) => {
    const sl = (String(t).match(/[\p{L}\p{N}_.\-]+/gu) || []).slice(0, n);
    return sl.concat(sl.slice(1).map((b, i) => `${sl[i]} ${b}`));
  };
  const eto = (t, rx, n) => golova(t, n).some((x) => rx.test(x));
  // табличка места накопления или "" — товар не отход
  window.OpasnyeOthody = (imya) => {
    const t = String(imya || "");
    if (O_NE.test(t)) return "";
    if (eto(t, O_BAT, 3)) return "II класс — батарейки";
    if (eto(t, O_AKK, 3)) {
      if (O_LITIY.test(t)) return "II класс — литий-ионные аккумуляторы";
      return O_SVINEC.test(t) || O_12V.test(t) ? "II класс — свинцовые аккумуляторы" : "II класс — литий-ионные аккумуляторы";
    }
    if (eto(t, O_LAMPA, 5)) {
      if (O_RTUT.test(t) && !O_LED.test(t)) return "I класс — люминесцентные (ртутьсодержащие) лампы";
      if (O_LED.test(t)) return "светодиодные лампы";
      if (/накалива|галоген/iu.test(t)) return "лампы накаливания";
      return "";
    }
    if (eto(t, O_SVET, 5) && O_LED.test(t) && !/фонар/iu.test(t)) return "светодиодные светильники";
    return "";
  };
  window.UTIL_OPAS = "Утиль · опасные отходы";
})();
